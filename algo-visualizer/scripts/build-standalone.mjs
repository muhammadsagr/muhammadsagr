// Bundles the UI + algorithm modules into ONE html file that works by double-click
// (file://), with no server and no build tools. Usage: node scripts/build-standalone.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');
const CORE = ['random.js', 'heap.js', 'sorting.js', 'pathfinding.js', 'cloud.js', 'benchmark.js'];

const stripModules = (code) =>
  code
    .replace(/^import\s[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*$/gm, '')
    .replace(/^export\s+(?=(const|let|function|class|async)\b)/gm, '');

export function buildStandalone() {
  const js = [...CORE.map((f) => `// ---- core/${f} ----\n${stripModules(read(`src/core/${f}`))}`), `// ---- app.js ----\n${stripModules(read('public/app.js'))}`].join('\n');
  if (/^\s*(import|export)\s/m.test(js)) throw new Error('unresolved import/export left in bundle');
  const html = read('public/index.html')
    .replace('<link rel="stylesheet" href="/style.css" />', () => `<style>\n${read('public/style.css')}</style>`)
    .replace('<script type="module" src="/app.js"></script>', () => `<script>\n"use strict";\n(() => {\n${js.replaceAll('</script', '<\\/script')}\n})();\n</script>`)
    .replace(/<footer>[\s\S]*?<\/footer>/, '<footer>Standalone build · generated by scripts/build-standalone.mjs</footer>');
  return `<!-- GENERATED FILE: edit public/ and src/core/, then run: npm run build:standalone -->\n${html}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(root, '..', 'algo_visualizer.html');
  fs.writeFileSync(out, buildStandalone());
  console.log(`wrote ${out}`);
}
