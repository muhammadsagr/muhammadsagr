def puzzles_for(level: int) -> list[Puzzle]:
    return [p for p in PUZZLES if p.level == level]


def pick(level: int, exclude: set[str] | None = None) -> Puzzle:
    """لغز عشوائي من المستوى، مع تفادي ما سبق حله إن أمكن."""
    pool = puzzles_for(level)
    fresh = [p for p in pool if p.title not in (exclude or set())]
    return random.choice(fresh or pool)
